// encryptKafkaSaslPassword encrypts the plain-text Kafka SASL password with the
// RSA public key fetched from DescribePublicEncryptKey. The returned public key
// is base64-encoded; the encrypted password is also returned base64-encoded.
func (r *IoaDeliveryServerResource) encryptKafkaSaslPassword(ctx context.Context, password string) (string, error) {
	keyResp, err := r.Client().UseIoaV20220601Client().DescribePublicEncryptKeyWithContext(ctx, ioav20220601.NewDescribePublicEncryptKeyRequest())
	if err != nil {
		return "", fmt.Errorf("DescribePublicEncryptKey failed: %w", err)
	}
	if keyResp == nil || keyResp.Response == nil || keyResp.Response.Data == nil || keyResp.Response.Data.PublicEncryptKey == nil {
		return "", fmt.Errorf("DescribePublicEncryptKey returned an empty response or an empty public key")
	}

	publicKeyBytes, err := base64.StdEncoding.DecodeString(*keyResp.Response.Data.PublicEncryptKey)
	if err != nil {
		return "", fmt.Errorf("error base64 decoding public key: %w", err)
	}

	// The key is expected to be a base64-encoded PKIX DER; fall back to a PEM block.
	parsed, parseErr := x509.ParsePKIXPublicKey(publicKeyBytes)
	if parseErr != nil {
		block, _ := pem.Decode(publicKeyBytes)
		if block == nil {
			return "", fmt.Errorf("error parsing public key: %w", parseErr)
		}
		parsed, parseErr = x509.ParsePKIXPublicKey(block.Bytes)
		if parseErr != nil {
			return "", fmt.Errorf("error parsing public key: %w", parseErr)
		}
	}

	publicKey, ok := parsed.(*rsa.PublicKey)
	if !ok {
		return "", fmt.Errorf("public key is not an RSA public key")
	}

	encrypted, err := rsa.EncryptPKCS1v15(rand.Reader, publicKey, []byte(password))
	if err != nil {
		return "", fmt.Errorf("error encrypting password: %w", err)
	}

	return base64.StdEncoding.EncodeToString(encrypted), nil
}

