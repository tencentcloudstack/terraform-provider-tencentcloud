// refreshData copies the cloud-side item into the nested data model.
func refreshDeliveryServerData(item *ioav20220601.DeliverServerItem) *IoaDeliveryServerDataModel {
	if item == nil {
		return nil
	}
	data := &IoaDeliveryServerDataModel{}
	if item.ID != nil {
		data.Id = types.Int64Value(int64(*item.ID))
	} else {
		data.Id = types.Int64Null()
	}
	data.Name = types.StringPointerValue(item.Name)
	data.Type = int64PointerValue(item.Type)
	data.Description = types.StringPointerValue(item.Description)
	data.TargetSyslogAddress = types.StringPointerValue(item.TargetSyslogAddress)
	data.TargetSyslogProtocol = types.StringPointerValue(item.TargetSyslogProtocol)
	if item.TargetSyslogPort != nil {
		data.TargetSyslogPort = types.Int64Value(int64(*item.TargetSyslogPort))
	} else {
		data.TargetSyslogPort = types.Int64Null()
	}
	data.SyslogFacility = types.StringPointerValue(item.SyslogFacility)
	data.TargetKafkaAddress = types.StringPointerValue(item.TargetKafkaAddress)
	data.TargetKafkaTopic = types.StringPointerValue(item.TargetKafkaTopic)
	data.KafkaVersion = types.StringPointerValue(item.KafkaVersion)
	data.KafkaSaslUserName = types.StringPointerValue(item.KafkaSaslUserName)
	// kafka_sasl_password is write-only and must never be persisted in state,
	// even if the describe API echoes the (encrypted) value back.
	data.KafkaSaslPassword = types.StringNull()
	data.TargetHttpUrl = types.StringPointerValue(item.TargetHttpUrl)
	if item.TargetHttpTimeout != nil {
		data.TargetHttpTimeout = types.Int64Value(int64(*item.TargetHttpTimeout))
	} else {
		data.TargetHttpTimeout = types.Int64Null()
	}
	data.ConnectorGroupId = types.StringPointerValue(item.ConnectorGroupId)
	data.ConnectorGroupName = types.StringPointerValue(item.ConnectorGroupName)
	data.KafkaSslEnable = types.BoolPointerValue(item.KafkaSSLEnable)
	data.SslSkipVerify = types.BoolPointerValue(item.SSLSkipVerify)
	return data
}

