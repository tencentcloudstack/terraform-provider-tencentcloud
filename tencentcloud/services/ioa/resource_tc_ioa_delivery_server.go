func int64Pointer(v int64) *int64 {
	return &v
}

func uint64Pointer(v int64) *uint64 {
	u := uint64(v)
	return &u
}

func int64PointerValue(v *int64) types.Int64 {
	if v == nil {
		return types.Int64Null()
	}
	return types.Int64Value(*v)
}

// Create handles `terraform apply` for new resources.
func (r *IoaDeliveryServerResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan IoaDeliveryServerResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	// Create path: the server id inside Data is ignored by the API.
	request := ioav20220601.NewModifyDeliveryServerRequest()
	request.Data = r.requestItem(plan.Data, nil)

	response, err := r.Client().UseIoaV20220601Client().ModifyDeliveryServerWithContext(ctx, request)
	if err != nil {
		resp.Diagnostics.AddError(
			"Error creating IOA delivery server",
			fmt.Sprintf("ModifyDeliveryServer failed: %v", err),
		)
		return
	}
	if response == nil || response.Response == nil || response.Response.Data == nil || response.Response.Data.ID == nil {
		resp.Diagnostics.AddError(
			"Error creating IOA delivery server",
			"ModifyDeliveryServer returned an empty response or an empty server id.",
		)
		return
	}

	serverId := *response.Response.Data.ID
	plan.Id = types.StringValue(strconv.FormatUint(serverId, 10))

	// Persist the identity before any follow-up read so `terraform destroy`
	// can still clean up the resource on a later failure.
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	item, err := r.readById(ctx, serverId)
	if err != nil {
		resp.Diagnostics.AddError(
			"Error reading IOA delivery server after create",
			fmt.Sprintf("DescribeDeliveryServer failed for server %d: %v", serverId, err),
		)
		return
	}
	if item == nil {
		resp.Diagnostics.AddError(
			"IOA delivery server not readable after create",
			fmt.Sprintf("server %d was created but cannot be read back", serverId),
		)
		return
	}
	plan.Data = refreshDeliveryServerData(item)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

// Read handles `terraform refresh` and post-apply state refresh.
func (r *IoaDeliveryServerResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state IoaDeliveryServerResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	serverId, err := strconv.ParseUint(state.Id.ValueString(), 10, 64)
	if err != nil {
		resp.Diagnostics.AddError(
			"Invalid resource ID",
			fmt.Sprintf("IOA delivery server id %q is not a valid server id", state.Id.ValueString()),
		)
		return
	}

	item, err := r.readById(ctx, serverId)
	if err != nil {
		resp.Diagnostics.AddError(
			"Error reading IOA delivery server",
			fmt.Sprintf("DescribeDeliveryServer failed for server %d: %v", serverId, err),
		)
		return
	}

	// DescribeDeliveryServer marks Data as nullable: a successful response
	// with a null Data means the server no longer exists on the cloud side.
	if item == nil {
		resp.State.RemoveResource(ctx)
		return
	}

	state.Data = refreshDeliveryServerData(item)
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

// Update handles in-place updates via the same ModifyDeliveryServer API,
// sending the id generated at create time as Data.ID.
func (r *IoaDeliveryServerResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan IoaDeliveryServerResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	var state IoaDeliveryServerResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	serverId, err := strconv.ParseUint(state.Id.ValueString(), 10, 64)
	if err != nil {
		resp.Diagnostics.AddError(
			"Invalid resource ID",
			fmt.Sprintf("IOA delivery server id %q is not a valid server id", state.Id.ValueString()),
		)
		return
	}

	// Update path: the API-generated id from create time is sent as Data.ID.
	request := ioav20220601.NewModifyDeliveryServerRequest()
	request.Data = r.requestItem(plan.Data, &serverId)

	if _, err := r.Client().UseIoaV20220601Client().ModifyDeliveryServerWithContext(ctx, request); err != nil {
		resp.Diagnostics.AddError(
			"Error updating IOA delivery server",
			fmt.Sprintf("ModifyDeliveryServer failed for server %d: %v", serverId, err),
		)
		return
	}

	item, err := r.readById(ctx, serverId)
	if err != nil {
		resp.Diagnostics.AddError(
			"Error reading IOA delivery server after update",
			fmt.Sprintf("DescribeDeliveryServer failed for server %d: %v", serverId, err),
		)
		return
	}
	if item == nil {
		resp.Diagnostics.AddError(
			"IOA delivery server not readable after update",
			fmt.Sprintf("server %d was updated but cannot be read back", serverId),
		)
		return
	}
	plan.Id = state.Id
	plan.Data = refreshDeliveryServerData(item)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

