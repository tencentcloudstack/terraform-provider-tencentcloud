// parseCustomGroupId splits `<zone_id>#<group_id>` into its two parts.
func parseCustomGroupId(id string) (zoneId string, groupId string, err error) {
	parts := strings.Split(id, tccommon.FILED_SP)
	if len(parts) != 2 || parts[0] == "" || parts[1] == "" {
		return "", "", fmt.Errorf("invalid custom group id %q, expected `<zone_id>%s<group_id>` format", id, tccommon.FILED_SP)
	}
	return parts[0], parts[1], nil
}

// requestGroupItems converts the typed plan list into the API item slice.
// ok=false means the conversion produced error diagnostics.
func (r *TeoCustomGroupResource) requestGroupItems(ctx context.Context, list types.List) (items []*teov20220901.CustomGroupItem, ok bool, diags diag.Diagnostics) {
	var models []TeoCustomGroupItemModel
	d := list.ElementsAs(ctx, &models, false)
	if d.HasError() {
		return nil, false, d
	}
	if len(models) == 0 {
		return nil, true, nil
	}
	out := make([]*teov20220901.CustomGroupItem, 0, len(models))
	for _, item := range models {
		out = append(out, &teov20220901.CustomGroupItem{
			Content:  item.Content.ValueStringPointer(),
			ItemType: item.ItemType.ValueStringPointer(),
		})
	}
	return out, true, nil
}

// Create handles `terraform apply` for new resources.
func (r *TeoCustomGroupResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan TeoCustomGroupResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	request := teov20220901.NewCreateCustomGroupRequest()
	request.ZoneId = plan.ZoneId.ValueStringPointer()
	request.GroupName = plan.GroupName.ValueStringPointer()
	request.GroupType = plan.GroupType.ValueStringPointer()

	items, ok, diags := r.requestGroupItems(ctx, plan.GroupItems)
	if !ok {
		resp.Diagnostics.Append(diags...)
		return
	}
	request.GroupItems = items

	response, err := r.Client().UseTeoV20220901Client().CreateCustomGroupWithContext(ctx, request)
	if err != nil {
		resp.Diagnostics.AddError(
			"Error creating TEO custom group",
			fmt.Sprintf("CreateCustomGroup failed: %v", err),
		)
		return
	}
	if response == nil || response.Response == nil || response.Response.GroupId == nil || *response.Response.GroupId == "" {
		resp.Diagnostics.AddError(
			"Error creating TEO custom group",
			"CreateCustomGroup returned an empty response or an empty group id.",
		)
		return
	}

	groupId := *response.Response.GroupId
	plan.GroupId = types.StringValue(groupId)
	plan.Id = types.StringValue(plan.ZoneId.ValueString() + tccommon.FILED_SP + groupId)

	// Persist the identity before the read-back so `terraform destroy` can
	// clean the group up even if the read fails.
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	item, err := r.readById(ctx, plan.ZoneId.ValueString(), groupId)
	if err != nil {
		resp.Diagnostics.AddError(
			"Error reading TEO custom group after create",
			fmt.Sprintf("DescribeCustomGroup failed for group %s: %v", groupId, err),
		)
		return
	}
	if item == nil {
		resp.Diagnostics.AddError(
			"TEO custom group not readable after create",
			fmt.Sprintf("group %s was created but cannot be read back", groupId),
		)
		return
	}
	refreshCustomGroupModel(ctx, &plan, item, plan.ZoneId.ValueString())
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

// Read handles `terraform refresh` and post-apply state refresh.
func (r *TeoCustomGroupResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state TeoCustomGroupResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	zoneId, groupId, err := parseCustomGroupId(state.Id.ValueString())
	if err != nil {
		resp.Diagnostics.AddError("Invalid resource ID", err.Error())
		return
	}

	item, err := r.readById(ctx, zoneId, groupId)
	if err != nil {
		resp.Diagnostics.AddError(
			"Error reading TEO custom group",
			fmt.Sprintf("DescribeCustomGroup failed for group %s: %v", groupId, err),
		)
		return
	}

	// A confirmed not-found (API error with the ResourceNotFound code, or a
	// successful response without a group id) drops the resource from state.
	// Any other failure is an error and keeps the state intact.
	if item == nil {
		resp.State.RemoveResource(ctx)
		return
	}

	refreshCustomGroupModel(ctx, &state, item, zoneId)
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

// Update handles in-place updates of the group name and group items.
func (r *TeoCustomGroupResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan TeoCustomGroupResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	var state TeoCustomGroupResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	zoneId, groupId, err := parseCustomGroupId(state.Id.ValueString())
	if err != nil {
		resp.Diagnostics.AddError("Invalid resource ID", err.Error())
		return
	}

	request := teov20220901.NewModifyCustomGroupRequest()
	request.ZoneId = helper.String(zoneId)
	request.GroupId = helper.String(groupId)

	// Cloud contract: an omitted GroupName/GroupItems keeps the previous
	// value, and GroupItemOperation defaults to Replace. GroupName and
	// GroupItems are required schema attributes, so they are always present
	// in a valid plan; the null checks below stay defensive.
	if !plan.GroupName.IsNull() && !plan.GroupName.IsUnknown() {
		request.GroupName = plan.GroupName.ValueStringPointer()
	}
	// GroupItemOperation is always sent explicitly so the update mode never
	// depends on the undocumented default behavior.
	request.GroupItemOperation = helper.String("Replace")
	if !plan.GroupItems.IsNull() && !plan.GroupItems.IsUnknown() {
		items, ok, diags := r.requestGroupItems(ctx, plan.GroupItems)
		if !ok {
			resp.Diagnostics.Append(diags...)
			return
		}
		if len(items) == 0 {
			// Whether "Replace + empty list" actually clears the cloud-side
			// item list is NOT confirmed by the API docs. Sending an omitted
			// GroupItems would keep the previous items (documented), which
			// would produce a permanent diff; silently keeping them would be
			// guessing a direction. Fail loudly instead.
			resp.Diagnostics.AddError(
				"Error updating TEO custom group",
				"group_items cannot be emptied: the behavior of clearing the item list with "+
					"an empty list is not confirmed by the TEO API. Remove the items you no "+
					"longer need individually, or recreate the group.",
			)
			return
		}
		request.GroupItems = items
	}

	retryErr := sdkresource.Retry(tccommon.WriteRetryTimeout, func() *sdkresource.RetryError {
		_, e := r.Client().UseTeoV20220901Client().ModifyCustomGroupWithContext(ctx, request)
		if e != nil {
			return tccommon.RetryError(e)
		}
		return nil
	})
	if retryErr != nil {
		resp.Diagnostics.AddError(
			"Error updating TEO custom group",
			fmt.Sprintf("ModifyCustomGroup failed for group %s: %v", groupId, retryErr),
		)
		return
	}

	item, err := r.readById(ctx, zoneId, groupId)
	if err != nil {
		resp.Diagnostics.AddError(
			"Error reading TEO custom group after update",
			fmt.Sprintf("DescribeCustomGroup failed for group %s: %v", groupId, err),
		)
		return
	}
	if item == nil {
		resp.Diagnostics.AddError(
			"TEO custom group not readable after update",
			fmt.Sprintf("group %s was updated but cannot be read back", groupId),
		)
		return
	}

	plan.Id = state.Id
	plan.ZoneId = state.ZoneId
	refreshCustomGroupModel(ctx, &plan, item, zoneId)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

// Delete handles resource deletion. The delete only removes the custom group
// itself; whether a referenced group (RefCount > 0) can be deleted is decided
// by the cloud API.
func (r *TeoCustomGroupResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state TeoCustomGroupResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	zoneId, groupId, err := parseCustomGroupId(state.Id.ValueString())
	if err != nil {
		resp.Diagnostics.AddError("Invalid resource ID", err.Error())
		return
	}

	request := teov20220901.NewDeleteCustomGroupRequest()
	request.ZoneId = helper.String(zoneId)
	request.GroupId = helper.String(groupId)

	retryErr := sdkresource.Retry(tccommon.WriteRetryTimeout, func() *sdkresource.RetryError {
		_, e := r.Client().UseTeoV20220901Client().DeleteCustomGroupWithContext(ctx, request)
		if e != nil {
			if tccommon.IsExpectError(e, []string{"ResourceNotFound"}) {
				// Confirmed already gone: swallow the error so delete is idempotent.
				return nil
			}
			return tccommon.RetryError(e)
		}
		return nil
	})
	if retryErr != nil {
		resp.Diagnostics.AddError(
			"Error deleting TEO custom group",
			fmt.Sprintf("DeleteCustomGroup failed for group %s: %v", groupId, retryErr),
		)
		return
	}
}

// ImportState is embedded via fw.WithImportByID; the imported id is the
// composite `<zone_id>#<group_id>` passthrough id.

// readById fetches the custom group by zone id + group id, following all pages
// of the GroupItems list (Limit defaults to 500 on the cloud side).
//
// Two different "empty" outcomes stay distinguishable:
//   - API failure (nil response / nil Response, or an API error) -> error
//   - confirmed not-found (ResourceNotFound error code, or a successful
//     response without a group id) -> (nil, nil) => "does not exist"
func (r *TeoCustomGroupResource) readById(ctx context.Context, zoneId, groupId string) (*teov20220901.DescribeCustomGroupResponseParams, error) {
	request := teov20220901.NewDescribeCustomGroupRequest()
	request.ZoneId = helper.String(zoneId)
	request.GroupId = helper.String(groupId)
	request.Limit = helper.Int64(500)

	var response *teov20220901.DescribeCustomGroupResponse
	retryErr := sdkresource.Retry(tccommon.ReadRetryTimeout, func() *sdkresource.RetryError {
		result, e := r.Client().UseTeoV20220901Client().DescribeCustomGroupWithContext(ctx, request)
		if e != nil {
			return tccommon.RetryError(e)
		}
		response = result
		return nil
	})
	if retryErr != nil {
		if tccommon.IsExpectError(retryErr, []string{"ResourceNotFound"}) {
			return nil, nil
		}
		return nil, retryErr
	}
	if response == nil || response.Response == nil {
		return nil, fmt.Errorf("DescribeCustomGroup returned an empty response for group %s", groupId)
	}
	if response.Response.GroupId == nil || *response.Response.GroupId == "" {
		return nil, nil
	}

	// Follow the pagination until every group item is collected. The loop
	// breaks when a page returns no progress to guard against a cloud side
	// that ignores the paging parameters.
	for response.Response.GroupItemTotalCount != nil &&
		int64(len(response.Response.GroupItems)) < *response.Response.GroupItemTotalCount {
		request.Offset = helper.Int64(int64(len(response.Response.GroupItems)))
		var next *teov20220901.DescribeCustomGroupResponse
		nextErr := sdkresource.Retry(tccommon.ReadRetryTimeout, func() *sdkresource.RetryError {
			result, e := r.Client().UseTeoV20220901Client().DescribeCustomGroupWithContext(ctx, request)
			if e != nil {
				return tccommon.RetryError(e)
			}
			next = result
			return nil
		})
		if nextErr != nil {
			return nil, nextErr
		}
		if next == nil || next.Response == nil || next.Response.GroupId == nil || *next.Response.GroupId == "" {
			return nil, fmt.Errorf("DescribeCustomGroup returned an empty response while paging group %s", groupId)
		}
		if len(next.Response.GroupItems) == 0 {
			break
		}
		response.Response.GroupItems = append(response.Response.GroupItems, next.Response.GroupItems...)
	}
	return response.Response, nil
}

// refreshCustomGroupModel copies the cloud-side response into the model. The
// zone id is not returned by the describe API, so it keeps the passed value
// (the configured one on create/update, the state one on read).
func refreshCustomGroupModel(ctx context.Context, m *TeoCustomGroupResourceModel, item *teov20220901.DescribeCustomGroupResponseParams, zoneId string) {
	if item == nil {
		return
	}
	m.ZoneId = types.StringValue(zoneId)
	m.GroupId = types.StringPointerValue(item.GroupId)
	m.GroupName = types.StringPointerValue(item.GroupName)
	m.GroupType = types.StringPointerValue(item.GroupType)
	m.GroupItemTotalCount = types.Int64PointerValue(item.GroupItemTotalCount)
	m.RefCount = types.Int64PointerValue(item.RefCount)

	items := make([]TeoCustomGroupItemModel, 0, len(item.GroupItems))
	for _, it := range item.GroupItems {
		items = append(items, TeoCustomGroupItemModel{
			Content:  types.StringPointerValue(it.Content),
			ItemType: types.StringPointerValue(it.ItemType),
		})
	}
	list, diags := types.ListValueFrom(ctx, customGroupItemObjectType(), items)
	if diags.HasError() {
		return
	}
	m.GroupItems = list
}

// customGroupItemObjectType returns the object type of a group_items element.
func customGroupItemObjectType() types.ObjectType {
	return types.ObjectType{
		AttrTypes: map[string]attr.Type{
			"content":   types.StringType,
			"item_type": types.StringType,
		},
	}
}
