// TeoCustomGroupResource implements resource.Resource for
// tencentcloud_teo_custom_group.
//
// Identity is composite: the cloud-side GroupId alone is not sufficient to
// locate the group because Describe/Modify/Delete all require ZoneId + GroupId,
// so the terraform resource id is `zone_id#group_id`.
//
// Update semantics (per API docs): ModifyCustomGroup keeps the previous value
// when GroupName or GroupItems is omitted, and GroupItemOperation defaults to
// Replace. This provider always sends GroupName, GroupItems and an explicit
// GroupItemOperation=Replace on update so the desired configuration fully
// replaces the cloud-side one (absent config field = keep the previous value,
// which matches the documented "keep" contract).
type TeoCustomGroupResource struct {
	fw.ResourceWithConfigure
	fw.WithImportByID
}

// TeoCustomGroupItemModel maps one entry of the nested group_items list.
type TeoCustomGroupItemModel struct {
	Content  types.String `tfsdk:"content"`
	ItemType types.String `tfsdk:"item_type"`
}

// TeoCustomGroupResourceModel maps the schema attributes.
type TeoCustomGroupResourceModel struct {
	Id                  types.String `tfsdk:"id"`
	ZoneId              types.String `tfsdk:"zone_id"`
	GroupId             types.String `tfsdk:"group_id"`
	GroupName           types.String `tfsdk:"group_name"`
	GroupType           types.String `tfsdk:"group_type"`
	GroupItems          types.List   `tfsdk:"group_items"`
	GroupItemTotalCount types.Int64  `tfsdk:"group_item_total_count"`
	RefCount            types.Int64  `tfsdk:"ref_count"`
}

